def main():
    conn = mysql.connector.connect(**DB)
    cur  = conn.cursor()

    # Create tables
    with open(os.path.join(os.path.dirname(__file__),"rebate_setup.sql")) as f:
        for stmt in f.read().split(";"):
            stmt = stmt.strip()
            if stmt:
                cur.execute(stmt)
    conn.commit()

    # Insert customer map
    cur.execute("DELETE FROM rebate_customer_map")
    for sold_to, hk_struct, lf_struct in CUSTOMER_MAP:
        if hk_struct:
            cur.execute(
                "INSERT IGNORE INTO rebate_customer_map (sold_to, brand, structure_name) VALUES (%s,'HK',%s)",
                (sold_to, hk_struct)
            )
        if lf_struct:
            cur.execute(
                "INSERT IGNORE INTO rebate_customer_map (sold_to, brand, structure_name) VALUES (%s,'LF',%s)",
                (sold_to, lf_struct)
            )
    print(f"Customer map rows inserted")

    # Insert structure tiers
    cur.execute("DELETE FROM rebate_structure")
    for row in STRUCTURES:
        cur.execute(
            "INSERT IGNORE INTO rebate_structure "
            "(structure_name, brand, period, unit, tier_order, threshold, rate) "
            "VALUES (%s,%s,%s,%s,%s,%s,%s)",
            row
        )
    print(f"Structure tier rows: {len(STRUCTURES)}")

    conn.commit()
    cur.close()
    conn.close()
    print("Done.")

if __name__ == "__main__":
    main()
