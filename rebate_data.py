# ──────────────────────────────────────────────────────────────
# 2. Rebate structure tiers
# fmt: (structure_name, brand, period, unit, [(threshold, rate%), ...])
# ──────────────────────────────────────────────────────────────
# Helper: period/unit encoded in name
#   _Q_ → unit=Q (qty)
#   _A_ → unit=A (amount)
# We treat all as Annual for simplicity (Q = quarterly, use ytd/3 logic in API)

def _tiers(struct_name, brand, period_unit, thresholds, rates):
    """period_unit: 'AQ'=Annual/Qty, 'AA'=Annual/Amt, 'QQ'=Quarterly/Qty"""
    period = period_unit[0]
    unit   = period_unit[1]
    rows = []
    for i,(t,r) in enumerate(zip(thresholds, rates), start=1):
        if t is not None and r is not None:
            rows.append((struct_name, brand, period, unit, i, float(t), float(r)))
    return rows

